class PredictRequest(BaseModel):
    image: str   # base64 data URI
    patient_name: str = "Unknown"
    patient_age: int = 0
    patient_gender: str = "Unspecified"

class ChatRequest(BaseModel):
    message: str

@app.post("/predict")
async def predict(req: PredictRequest):
    if model is None:
        raise HTTPException(status_code=503, detail="AI model failed to load.")

    # Decode image
    try:
        img = decode_base64_image(req.image)
    except Exception as e:
        raise HTTPException(status_code=400, detail=f"Invalid image data: {e}")

    # Run YOLO with a lower confidence threshold for better sensitivity
    # Also ensure imgsz=640 to match training
    results = model.predict(img, verbose=False, conf=0.20, imgsz=640)[0]

    # Analytics
    num_det   = len(results.boxes)
    found     = num_det > 0
    max_conf  = float(results.boxes.conf.max()) if found else 0.0
    
    # Calculate infected area percentage
    h, w = img.shape[:2]
    total_area = h * w
    infected_area = 0
    if found:
        for box in results.boxes.xywh: # x, y, width, height format
            infected_area += float(box[2] * box[3])
    
    coverage_pct = (infected_area / total_area) * 100
    coverage_str = f"{coverage_pct:.1f}%" if found else "0%"

    # Annotated image
    annotated = results.plot(labels=True, conf=True, line_width=3)
    annotated_b64 = encode_image_to_base64(annotated)

    # Report
    report = generate_report(found, max_conf, num_det)
    report['coverage'] = coverage_str

    # Save to Database
    try:
        conn = sqlite3.connect("varicose.db")
        c = conn.cursor()
        c.execute("INSERT INTO patients (name, age, gender) VALUES (?, ?, ?)", 
                  (req.patient_name, req.patient_age, req.patient_gender))
        patient_id = c.lastrowid
        
        c.execute("INSERT INTO scans (patient_id, date, status, confidence, detections, risk) VALUES (?, ?, ?, ?, ?, ?)",
                  (patient_id, report['date'], report['status'], report['confidence'], report['detections'], report['risk']))
        conn.commit()
        conn.close()
    except Exception as e:
        print(f"[ERR] DB Insert failed: {e}")

    return JSONResponse({
        "success": True,
        "prediction": {
            "found":            found,
            "detections":       num_det,
            "confidence":       f"{max_conf * 100:.1f}%",
            "coverage":         coverage_str,
            "annotated_image":  annotated_b64,
        },
        "report": report,
    })

@app.get("/api/history")
def get_history():
    try:
        conn = sqlite3.connect("varicose.db")
        conn.row_factory = sqlite3.Row
        c = conn.cursor()
        c.execute('''
            SELECT p.name, p.age, p.gender, s.date, s.status, s.confidence, s.risk 
            FROM scans s
            JOIN patients p ON s.patient_id = p.id
            ORDER BY s.id DESC LIMIT 50
        ''')
        rows = [dict(r) for r in c.fetchall()]
        conn.close()
        return {"history": rows}
    except Exception as e:
        return {"history": [], "error": str(e)}

@app.post("/api/clear_history")
def clear_history():
    try:
        conn = sqlite3.connect("varicose.db")
        c = conn.cursor()
        c.execute("DELETE FROM scans")
        c.execute("DELETE FROM patients")
        conn.commit()
        conn.close()
        return {"success": True}
    except Exception as e:
        return {"success": False, "error": str(e)}

